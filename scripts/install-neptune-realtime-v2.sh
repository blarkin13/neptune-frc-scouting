#!/usr/bin/env python3
"""Dependency-free WebSocket relay for Neptune realtime notifications.

Robot Recall keeps its existing public six-digit room behavior (100000-999999).
Match Scouting uses reserved leading-zero rooms (000001-099999) that require a
short-lived HMAC token generated by authenticated Neptune PHP.

The relay never carries authoritative scouting/game state. Clients send a small
notification; receivers then fetch authoritative state from Neptune's existing
HTTP APIs.
"""

import asyncio
import base64
import hashlib
import hmac
import json
import os
import re
import struct
import time
from collections import defaultdict, deque
from urllib.parse import urlsplit, parse_qs

HOST = os.environ.get("NEPTUNE_RR_WS_HOST", "127.0.0.1")
PORT = int(os.environ.get("NEPTUNE_RR_WS_PORT", "8765"))
SECRET_FILE = os.environ.get("NEPTUNE_REALTIME_SECRET_FILE", "/etc/neptune/realtime.secret")
GUID = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"
PRIVATE_SCOPE = "scouting"
PRIVATE_TOKEN_VERSION = "v1"
PRIVATE_MAX_FUTURE_SECONDS = 600
PRIVATE_CLOCK_SKEW_SECONDS = 30
rooms = defaultdict(set)
clients = set()


def load_private_secret() -> bytes:
    try:
        with open(SECRET_FILE, "rb") as fh:
            secret = fh.read().strip()
        if len(secret) < 32:
            return b""
        return secret
    except OSError:
        return b""


PRIVATE_SECRET = load_private_secret()


def text_frame(text: str, opcode: int = 0x1) -> bytes:
    payload = text.encode("utf-8") if isinstance(text, str) else bytes(text)
    n = len(payload)
    head = bytes([0x80 | opcode])
    if n < 126:
        return head + bytes([n]) + payload
    if n <= 65535:
        return head + bytes([126]) + struct.pack("!H", n) + payload
    return head + bytes([127]) + struct.pack("!Q", n) + payload


async def read_frame(reader: asyncio.StreamReader):
    first = await reader.readexactly(2)
    b1, b2 = first
    opcode = b1 & 0x0F
    masked = bool(b2 & 0x80)
    length = b2 & 0x7F
    if length == 126:
        length = struct.unpack("!H", await reader.readexactly(2))[0]
    elif length == 127:
        length = struct.unpack("!Q", await reader.readexactly(8))[0]
    if length > 65536:
        raise ValueError("frame too large")
    mask = await reader.readexactly(4) if masked else b""
    payload = await reader.readexactly(length) if length else b""
    if masked:
        payload = bytes(b ^ mask[i % 4] for i, b in enumerate(payload))
    return opcode, payload


def private_token_message(room: str, expires: int) -> bytes:
    return f"{PRIVATE_TOKEN_VERSION}|{PRIVATE_SCOPE}|{room}|{expires}".encode("utf-8")


def private_room_authorized(room: str, query: dict) -> bool:
    if not PRIVATE_SECRET:
        return False
    scope = str(query.get("scope", [""])[0])
    token = str(query.get("token", [""])[0])
    expires_raw = str(query.get("expires", [""])[0])
    if scope != PRIVATE_SCOPE or not token or not expires_raw.isdigit():
        return False
    expires = int(expires_raw)
    now = int(time.time())
    if expires < now - PRIVATE_CLOCK_SKEW_SECONDS:
        return False
    if expires > now + PRIVATE_MAX_FUTURE_SECONDS:
        return False
    expected = hmac.new(PRIVATE_SECRET, private_token_message(room, expires), hashlib.sha256).hexdigest()
    return hmac.compare_digest(token, expected)


def authorize_room(target: str) -> str:
    query = parse_qs(urlsplit(target).query)
    room = str(query.get("room", [""])[0])
    if not re.fullmatch(r"\d{6}", room):
        raise ValueError("six-digit room required")
    number = int(room)
    if 100000 <= number <= 999999:
        # Existing Robot Recall behavior: intentionally public join rooms.
        return room
    if 1 <= number <= 99999:
        # Reserved Match Scouting room range. Authentication is mandatory.
        if not private_room_authorized(room, query):
            raise ValueError("private room authorization failed")
        return room
    raise ValueError("room out of range")


class Client:
    __slots__ = ("reader", "writer", "room", "recent", "closed")

    def __init__(self, reader, writer, room):
        self.reader = reader
        self.writer = writer
        self.room = room
        self.recent = deque()
        self.closed = False

    def __hash__(self):
        return id(self)

    async def send_json(self, payload):
        if self.closed:
            return
        self.writer.write(text_frame(json.dumps(payload, separators=(",", ":"))))
        await self.writer.drain()

    async def send_control(self, opcode, payload=b""):
        if self.closed:
            return
        self.writer.write(text_frame(payload, opcode=opcode))
        await self.writer.drain()

    def rate_ok(self):
        now = time.monotonic()
        while self.recent and now - self.recent[0] > 1.0:
            self.recent.popleft()
        if len(self.recent) >= 24:
            return False
        self.recent.append(now)
        return True


async def broadcast(room: str, source: str, sender=None):
    # Keep the Robot Recall-compatible poke envelope. Match Scouting's browser
    # client normalizes `source` into its application event type.
    payload = {"type": "poke", "source": source[:24], "ts": int(time.time() * 1000)}
    dead = []
    for client in list(rooms.get(room, ())):
        try:
            await client.send_json(payload)
        except Exception:
            dead.append(client)
    for client in dead:
        await drop(client)


async def drop(client: Client):
    if client.closed:
        return
    client.closed = True
    clients.discard(client)
    rooms[client.room].discard(client)
    if not rooms[client.room]:
        rooms.pop(client.room, None)
    try:
        client.writer.close()
        await client.writer.wait_closed()
    except Exception:
        pass


async def handle(reader: asyncio.StreamReader, writer: asyncio.StreamWriter):
    client = None
    try:
        request = await asyncio.wait_for(reader.readuntil(b"\r\n\r\n"), timeout=5)
        if len(request) > 16384:
            raise ValueError("header too large")
        lines = request.decode("latin1").split("\r\n")
        method, target, _ = lines[0].split(" ", 2)
        if method.upper() != "GET":
            raise ValueError("GET required")
        headers = {}
        for line in lines[1:]:
            if ":" in line:
                k, v = line.split(":", 1)
                headers[k.strip().lower()] = v.strip()
        key = headers.get("sec-websocket-key", "")
        if not key or "websocket" not in headers.get("upgrade", "").lower():
            raise ValueError("websocket upgrade required")
        room = authorize_room(target)
        accept = base64.b64encode(hashlib.sha1((key + GUID).encode("ascii")).digest()).decode("ascii")
        writer.write((
            "HTTP/1.1 101 Switching Protocols\r\n"
            "Upgrade: websocket\r\n"
            "Connection: Upgrade\r\n"
            f"Sec-WebSocket-Accept: {accept}\r\n\r\n"
        ).encode("ascii"))
        await writer.drain()

        client = Client(reader, writer, room)
        clients.add(client)
        rooms[room].add(client)
        await client.send_json({"type": "hello", "room": room, "ts": int(time.time() * 1000)})

        while True:
            opcode, payload = await read_frame(reader)
            if opcode == 0x8:
                break
            if opcode == 0x9:
                await client.send_control(0xA, payload)
                continue
            if opcode == 0xA:
                continue
            if opcode != 0x1 or not client.rate_ok():
                continue
            source = "state"
            try:
                msg = json.loads(payload.decode("utf-8", "replace"))
                if isinstance(msg, dict):
                    source = str(msg.get("type") or "state")
            except Exception:
                pass
            await broadcast(room, source, client)
    except (asyncio.IncompleteReadError, ConnectionResetError, BrokenPipeError):
        pass
    except Exception:
        try:
            writer.write(b"HTTP/1.1 400 Bad Request\r\nConnection: close\r\nContent-Length: 0\r\n\r\n")
            await writer.drain()
        except Exception:
            pass
    finally:
        if client:
            await drop(client)
        else:
            try:
                writer.close()
                await writer.wait_closed()
            except Exception:
                pass


async def heartbeat():
    while True:
        await asyncio.sleep(20)
        dead = []
        for client in list(clients):
            try:
                await client.send_control(0x9, b"np")
            except Exception:
                dead.append(client)
        for client in dead:
            await drop(client)


async def main():
    server = await asyncio.start_server(handle, HOST, PORT, limit=32768)
    auth_state = "enabled" if PRIVATE_SECRET else f"DISABLED (missing/short {SECRET_FILE})"
    print(f"Neptune realtime relay listening on {HOST}:{PORT}; private_auth={auth_state}", flush=True)
    asyncio.create_task(heartbeat())
    async with server:
        await server.serve_forever()


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass
PYRELAY

